// Generate the browser's compact replay-evidence record from the authoritative scoreboard.
//
//     node web/tools/gen-readiness.mjs
//     node web/tools/gen-readiness.mjs --check
//
// The playable page must not copy scoreboard numbers into prose by hand. This generator
// deliberately carries only evidence the page can explain in a small diagnostic card; the
// complete record remains schema/replay-validation.json.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, '..', '..');
const SOURCE = join(REPO, 'schema', 'replay-validation.json');
const OUTPUT = join(REPO, 'web', 'public', 'js', 'play', 'readiness.gen.js');

const record = JSON.parse(readFileSync(SOURCE, 'utf8'));
const files = record.files ?? [];
const checked = files.filter((f) => f.turns_checksummed > 0);
const world = record.totals?.per_channel?.world;
if (!world || checked.length !== record.totals.files_with_checksums) {
  throw new Error('replay-validation.json has no coherent world/checksummed-file record');
}

const range = (values) => ({ min: Math.min(...values), max: Math.max(...values) });
const divergenceTurns = [...new Set(checked.map((f) => f.channels?.world?.first_divergence_turn))]
  .filter((v) => Number.isInteger(v)).sort((a, b) => a - b);

const evidence = {
  source: 'schema/replay-validation.json',
  generatedBy: record.generated_by,
  files: record.totals.files,
  prefixesParsed: files.filter((f) => f.initial?.prefix_bytes_walked > 0).length,
  filesWithChecksums: record.totals.files_with_checksums,
  turns: record.totals.turns,
  checksumPackets: record.totals.checksum_packets,
  crossplay: record.totals.crossplay_by_group,
  world: {
    comparisons: world.compares,
    nontrivial: world.nontrivial_compares,
    matches: world.matches,
    bestSurvivedTurns: world.best_survived_turns,
    firstDivergenceTurns: divergenceTurns,
    walkedBytes: range(checked.map((f) => f.channels.world.our_bytes_walked)),
    unsourcedBytes: range(checked.map((f) => f.channels.world.our_unsourced_walked)),
  },
};

if (evidence.prefixesParsed !== evidence.files
    || evidence.world.nontrivial !== evidence.world.comparisons
    || !evidence.world.comparisons) {
  throw new Error('refusing to generate a non-empty-world claim from incomplete evidence');
}

const rendered = `// Generated by web/tools/gen-readiness.mjs from ${evidence.source}.\n`
  + '// Do not edit by hand; use --check in smoke gates.\n\n'
  + `export const REPLAY_EVIDENCE = Object.freeze(${JSON.stringify(evidence, null, 2)});\n`;

if (process.argv.includes('--check')) {
  const current = readFileSync(OUTPUT, 'utf8');
  if (current !== rendered) {
    console.error('stale generated readiness evidence: run node web/tools/gen-readiness.mjs');
    process.exit(1);
  }
  console.log('readiness evidence is current');
} else {
  writeFileSync(OUTPUT, rendered);
  console.log(`wrote ${OUTPUT}`);
}
