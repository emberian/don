    0x13: ['ox', 'queued'],                  // GatherCommand   — send a worker to a node
    0x18: ['type', 'num'],                   // QueueUpCommand  — train/research at a producer
    0x19: ['x', 'y', 'x2', 'y2', 'type'],    // BuildCommand    — place a building
