#!/usr/bin/env python3
"""Generate crates/don-replay/src/walk_gen.rs from schema/state-schema.json.

schema/state-schema.json is the machine-derived `DataWalk` traversal: 278
classes, 1,421 ordered ops, 899 byte ranges (647 resolved), intersected with the
PDB type layout. It is *the* definition of sim-critical state, so the walker in
this crate is generated from it rather than typed by hand -- typing it by hand is
exactly how a traversal silently drifts from the binary.

Re-run after any change to schema/state-schema.json:

    python3 crates/don-replay/gen/gen_walk.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[3]
SRC = ROOT / "schema" / "state-schema.json"
OUT = ROOT / "crates" / "don-replay" / "src" / "walk_gen.rs"


def rs_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    doc = json.load(SRC.open())
    classes = doc["classes"]
    meta = doc["_meta"]

    names = sorted(classes)
    idx = {n: i for i, n in enumerate(names)}

    lines = []
    w = lines.append
    w("// GENERATED by crates/don-replay/gen/gen_walk.py from schema/state-schema.json.")
    w("// Do not edit by hand; edit the generator or the schema.")
    w("//")
    w("// The engine's DataWalk traversal, machine-derived: every walk_data override,")
    w("// its ordered ops, and the this-relative byte range each op walks. See")
    w("// schema/state-schema.json `_meta.caveats` -- the extraction is a linear scan")
    w("// with no dataflow join, so ops whose operands cross a branch are Unresolved")
    w("// and are counted, never guessed.")
    w("")
    w("use crate::walk::{WalkOp, WalkSpec};")
    w("")
    w(f"pub const NUM_CLASSES: usize = {len(names)};")
    w(f"/// `_meta.counts.ordered_ops` in the source schema.")
    w(f"pub const ORDERED_OPS: usize = {meta['counts']['ordered_ops']};")
    w(f"pub const RESOLVED_BYTE_RANGES: usize = {meta['counts']['resolved_byte_ranges']};")
    w(f"pub const TOTAL_SIM_CRITICAL_BYTES: usize = {meta['counts']['total_sim_critical_bytes']};")
    w("")

    for n in names:
        c = classes[n]
        w(f"static OPS_{idx[n]}: &[WalkOp] = &[")
        for o in c.get("ops", []):
            k = o["kind"]
            if k == "bytes":
                b, e = o.get("begin"), o.get("end")
                if isinstance(b, int) and isinstance(e, int) and e >= b >= 0:
                    w(f"    WalkOp::Bytes {{ begin: {b}, end: {e} }},")
                elif o.get("bytes") and not isinstance(b, int):
                    # a resolved length with an unresolved base (a stack temporary)
                    w(f"    WalkOp::Scratch {{ bytes: {int(o['bytes'])} }},")
                else:
                    w("    WalkOp::Unresolved,")
            elif k == "tag":
                w("    WalkOp::Tag,")
            elif k == "sub_object":
                t = o.get("target_class")
                if t in idx:
                    w(f"    WalkOp::Sub {{ class: {idx[t]} }},")
                else:
                    w(f"    WalkOp::SubUnknown {{ va: 0x{int(o['target'], 16):08x} }},")
            elif k == "virtual":
                w("    WalkOp::Virtual,")
            else:
                w("    WalkOp::Unresolved,")
        w("];")
    w("")

    w("pub static SPECS: [WalkSpec; NUM_CLASSES] = [")
    for n in names:
        c = classes[n]
        va = c.get("walk_data")
        va_i = int(va, 16) if isinstance(va, str) else 0
        sz = c.get("sizeof") or 0
        wb = c.get("walked_bytes") or 0
        w(
            f"    WalkSpec {{ name: {rs_str(n)}, walk_data_va: 0x{va_i:08x}, "
            f"sizeof: {sz}, walked_bytes: {wb}, ops: OPS_{idx[n]} }},"
        )
    w("];")
    w("")

    w("/// Class index by name, for the channel walkers. Linear search over 278")
    w("/// entries at start-up only; kept simple rather than perfect-hashed.")
    w("pub fn class_index(name: &str) -> Option<usize> {")
    w("    SPECS.iter().position(|s| s.name == name)")
    w("}")

    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(lines)} lines, {len(names)} classes)")


if __name__ == "__main__":
    main()
