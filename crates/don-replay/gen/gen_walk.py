#!/usr/bin/env python3
"""Generate crates/don-replay/src/walk_gen.rs from schema/state-schema.json.

schema/state-schema.json is the machine-derived `DataWalk` traversal: 278
classes, 1,421 ordered ops, 899 byte ranges (647 resolved), intersected with the
PDB type layout. It is *the* definition of sim-critical state, so the walker in
this crate is generated from it rather than typed by hand -- typing it by hand is
exactly how a traversal silently drifts from the binary.

Re-run after any change to schema/state-schema.json:

    python3 crates/don-replay/gen/gen_walk.py

CI/audits can verify that the checked-in Rust is exact without rewriting it:

    python3 crates/don-replay/gen/gen_walk.py --check
"""
import argparse
import json
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[3]
SRC = ROOT / "schema" / "state-schema.json"
OUT = ROOT / "crates" / "don-replay" / "src" / "walk_gen.rs"


def rs_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generated_source() -> str:
    doc = json.load(SRC.open())
    classes = doc["classes"]
    meta = doc["_meta"]

    names = sorted(classes)
    idx = {n: i for i, n in enumerate(names)}

    lines = []
    w = lines.append
    w("// GENERATED by crates/don-replay/gen/gen_walk.py from schema/state-schema.json.")
    w("// Do not edit by hand; edit the generator or the schema.")
    w("//")
    w("// The engine's DataWalk traversal, machine-derived: every walk_data override,")
    w("// its ordered ops, and the this-relative byte range each op walks. See")
    w("// schema/state-schema.json `_meta.caveats` -- the extraction is a linear scan")
    w("// with no dataflow join, so ops whose operands cross a branch are Unresolved")
    w("// and are counted, never guessed.")
    w("")
    w("use crate::walk::{WalkOp, WalkSpec};")
    w("")
    w(f"pub const NUM_CLASSES: usize = {len(names)};")
    w(f"/// `_meta.counts.ordered_ops` in the source schema.")
    w(f"pub const ORDERED_OPS: usize = {meta['counts']['ordered_ops']};")
    w(f"pub const RESOLVED_BYTE_RANGES: usize = {meta['counts']['resolved_byte_ranges']};")
    w(f"pub const TOTAL_SIM_CRITICAL_BYTES: usize = {meta['counts']['total_sim_critical_bytes']};")
    w("")

    for n in names:
        c = classes[n]
        w(f"static OPS_{idx[n]}: &[WalkOp] = &[")
        for o in c.get("ops", []):
            k = o["kind"]
            if k == "bytes":
                b, e = o.get("begin"), o.get("end")
                if o.get("base"):
                    # A range on a GLOBAL object, not on `this`. The offsets are
                    # resolved but they are meaningless against an object image,
                    # so emitting them as this-relative would silently hash the
                    # wrong bytes. Keep the length; refuse the range.
                    # `nb`, not `n`: `n` is the enclosing class name and
                    # shadowing it here is a trap for the next edit.
                    nb = int(o["bytes"]) if o.get("bytes") else 0
                    w(f'    WalkOp::Global {{ bytes: {nb}, base: "{o["base"]}" }},')
                elif isinstance(b, int) and isinstance(e, int) and e >= b >= 0:
                    w(f"    WalkOp::Bytes {{ begin: {b}, end: {e} }},")
                elif o.get("bytes"):
                    # A resolved length with an unresolved base: a stack
                    # temporary, or a pointer the linear scan could not track.
                    w(f"    WalkOp::Scratch {{ bytes: {int(o['bytes'])} }},")
                else:
                    w("    WalkOp::Unresolved,")
            elif k == "tag":
                w("    WalkOp::Tag,")
            elif k == "sub_object":
                t = o.get("target_class")
                if t not in idx:
                    w(f"    WalkOp::SubUnknown {{ va: 0x{int(o['target'], 16):08x} }},")
                    continue
                # WHERE the sub-object lives decides whether the op is
                # executable against a flat object image. `['this', N]` is an
                # embedded base or member at this+N and is executable; anything
                # else names a receiver we do not hold (a heap pointer, a global,
                # an immediate address, a stack temporary), and executing it at
                # offset 0 -- which this generator used to do for all 368 sub
                # ops -- hashes the WRONG bytes with full confidence the moment
                # an image stops being all zeroes.
                base = o.get("this")
                kind = base[0] if isinstance(base, list) and base else None
                off = base[1] if isinstance(base, list) and len(base) > 1 else None
                if kind == "this" and isinstance(off, int) and off >= 0:
                    w(f"    WalkOp::Sub {{ class: {idx[t]}, at: {off} }},")
                elif kind == "thisload" and isinstance(off, int) and off >= 0:
                    w(f"    WalkOp::SubPtr {{ class: {idx[t]}, at: {off} }},")
                else:
                    w(f"    WalkOp::SubUnbased {{ class: {idx[t]} }},")
            elif k == "virtual":
                w("    WalkOp::Virtual,")
            else:
                w("    WalkOp::Unresolved,")
        w("];")
    w("")

    w("pub static SPECS: [WalkSpec; NUM_CLASSES] = [")
    for n in names:
        c = classes[n]
        va = c.get("walk_data")
        va_i = int(va, 16) if isinstance(va, str) else 0
        sz = c.get("sizeof") or 0
        wb = c.get("walked_bytes") or 0
        w(
            f"    WalkSpec {{ name: {rs_str(n)}, walk_data_va: 0x{va_i:08x}, "
            f"sizeof: {sz}, walked_bytes: {wb}, ops: OPS_{idx[n]} }},"
        )
    w("];")
    w("")

    w("/// Class index by name, for the channel walkers. Linear search over 278")
    w("/// entries at start-up only; kept simple rather than perfect-hashed.")
    w("pub fn class_index(name: &str) -> Option<usize> {")
    w("    SPECS.iter().position(|s| s.name == name)")
    w("}")

    source = "\n".join(lines) + "\n"
    # The checked-in artifact is rustfmt-formatted. Formatting here makes
    # regeneration deterministic and lets `--check` compare exact bytes rather
    # than accepting a semantically-equal but mechanically stale table.
    try:
        proc = subprocess.run(
            ["rustfmt", "--edition", "2021", "--emit", "stdout"],
            input=source,
            text=True,
            capture_output=True,
            check=True,
        )
    except FileNotFoundError as exc:
        raise SystemExit("gen_walk.py: rustfmt is required") from exc
    except subprocess.CalledProcessError as exc:
        raise SystemExit(f"gen_walk.py: rustfmt failed:\n{exc.stderr}") from exc
    return proc.stdout


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--check",
        action="store_true",
        help="fail if walk_gen.rs is not the exact generated, rustfmt-formatted output",
    )
    args = ap.parse_args()

    source = generated_source()
    if args.check:
        current = OUT.read_text() if OUT.exists() else None
        if current != source:
            raise SystemExit(
                f"stale generated walker: run python3 {pathlib.Path(__file__).relative_to(ROOT)}"
            )
        print(f"up to date: {OUT}")
        return

    OUT.write_text(source)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
