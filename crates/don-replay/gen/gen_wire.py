#!/usr/bin/env python3
"""Generate crates/don-replay/src/wire_gen.rs from schema/command-wire.json.

The command field table is derived (PDB type stream -> schema/command-wire.json),
so it is generated rather than typed by hand. Re-run after any change to
schema/command-wire.json:

    python3 crates/don-replay/gen/gen_wire.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[3]
SRC = ROOT / "schema" / "command-wire.json"
OUT = ROOT / "crates" / "don-replay" / "src" / "wire_gen.rs"

# C type -> (FieldKind, byte width). Anything not listed is Opaque and carries
# only its offset; nothing in this crate reads an Opaque field.
SCALARS = {
    "char": ("I8", 1),
    "unsigned char": ("U8", 1),
    "short": ("I16", 2),
    "unsigned short": ("U16", 2),
    "int": ("I32", 4),
    "unsigned long": ("U32", 4),
    "float": ("F32", 4),
    # Coord and OrderIndex are one-int wrappers (see README-LLM: Coord/WCoord/
    # TCoord each wrap a single int). QueuePos is a 4-byte struct we do not read.
    "Coord": ("I32", 4),
    "OrderIndex": ("I32", 4),
}


def main() -> None:
    cmds = json.load(SRC.open())
    by_op = {c["op"]: c for c in cmds}
    n = max(by_op) + 1
    assert n == 82, n

    lines = []
    w = lines.append
    w("// GENERATED by crates/don-replay/gen/gen_wire.py from schema/command-wire.json.")
    w("// Do not edit by hand; edit the generator or the schema.")
    w("//")
    w("// Source: 82 CommandTypes opcodes with the exact field layout the PDB type")
    w("// stream gives for each *Command struct, cross-checked against the byte length")
    w("// each handler returns (schema/command-wire.json).")
    w("")
    w("use crate::wire::{Field, FieldKind};")
    w("")
    w(f"pub const NUM_OPCODES: usize = {n};")
    w("")

    # per-op field slices
    for op in range(n):
        c = by_op.get(op)
        fields = c.get("fields", []) if c else []
        w(f"pub(crate) static F_{op:02X}: &[Field] = &[")
        for f in fields:
            kind, width = SCALARS.get(f["type"], ("Opaque", 0))
            name = f["name"].replace('"', "")
            w(
                f'    Field {{ off: {f["off"]}, kind: FieldKind::{kind}, '
                f'width: {width}, name: "{name}", ty: "{f["type"]}" }},'
            )
        w("];")
    w("")

    w("pub static COMMAND_FIELDS: [&[Field]; NUM_OPCODES] = [")
    for op in range(n):
        w(f"    F_{op:02X},")
    w("];")
    w("")

    w("/// `*Command` struct name per opcode, from the PDB.")
    w("pub static COMMAND_STRUCT: [&str; NUM_OPCODES] = [")
    for op in range(n):
        c = by_op.get(op)
        w(f'    "{c["struct"] if c else "?"}",')
    w("];")
    w("")

    w("/// `CommandPackage::process_*` handler name per opcode, from the PDB.")
    w("pub static COMMAND_METHOD: [&str; NUM_OPCODES] = [")
    for op in range(n):
        c = by_op.get(op)
        w(f'    "{c["method"] if c else "?"}",')
    w("];")
    w("")

    w("/// `sizeof(*Command)` per opcode. NOT the wire length for the three")
    w("/// variable-length opcodes (0x00, 0x33, 0x44) -- use `don_net::Command::wire_len`.")
    w("pub static COMMAND_SIZEOF: [u16; NUM_OPCODES] = [")
    for op in range(n):
        c = by_op.get(op)
        w(f'    {c["size"] if c else 0},')
    w("];")

    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(lines)} lines, {n} opcodes)")


if __name__ == "__main__":
    main()
