"""Generate crates/don-state/src/generated/layout.rs from the retail PDB.

Uses re/scripts/pdb_layout.py to flatten each class into leaf fields
(offset, size, name) and emits a static lookup table consumed by
`svx-diff` for offset->field attribution of differing spans.

Classes are limited to the ones the don-state walkers actually touch
(the `class` tokens embedded in Loader span paths in sections.rs).

    uv run --quiet python crates/don-state/gen/gen_layout.py
"""
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
sys.path.insert(0, os.path.join(REPO, "re", "scripts"))

from pdb_layout import tpi, flatten  # noqa: E402

# Classes the walkers touch (span-path class tokens in sections.rs) that
# have PDB layouts worth attributing to. Missing names are skipped with a
# warning rather than failing generation.
CLASSES = [
    "WalkDataGame", "GameInfo", "Game", "Tribe", "Army", "City", "Form",
    "Object", "SubObject", "Unit", "UnitData", "Build", "BuildData",
    "Animal", "Guy", "Group", "Leader", "LeaderData", "World", "Land",
    "Caravan", "Hero", "Herd", "Item", "Fort", "Dock", "OilWell",
    "Supply", "Wonder", "DeathObj", "OrderList", "PathData", "HotKeyGroup",
    "GraphicEvent", "GraphicEvents", "Scene", "FarmStruct", "SelectGroup",
    "Option", "CommandPackage", "River", "Region", "WCoordData",
    "MessageWinEntry", "ScenarioData", "ConquestLeader", "ConquestNode",
    "ConquestColony", "ConquestStyle", "AchieveData", "GoodItem",
]

OUT = os.path.join(os.path.dirname(__file__), "..", "src", "generated", "layout.rs")


def rust_name(name):
    return "CLS_" + "".join(
        c if c.isalnum() else "_" for c in name).upper()


def main():
    t = tpi()
    layouts = []
    for cls in CLASSES:
        L = t.layout(cls)
        if not L:
            print(f"warn: no PDB layout for {cls}, skipping", file=sys.stderr)
            continue
        fields = [f for f in flatten(cls) if f.get("leaf") and f.get("off") is not None]
        layouts.append((cls, L["size"], fields))

    out = [
        "// Generated by crates/don-state/gen/gen_layout.py from ron-bin/sbl/rise.pdb.",
        "// Do not edit by hand.",
        "",
        "/// One leaf field of a retail class layout.",
        "pub struct FieldDef {",
        "    pub off: u32,",
        "    pub size: u32,",
        "    pub name: &'static str,",
        "}",
        "",
        "/// A flattened retail class layout (base classes inlined).",
        "pub struct ClassLayout {",
        "    pub name: &'static str,",
        "    pub sizeof: u32,",
        "    pub fields: &'static [FieldDef],",
        "}",
        "",
    ]
    for cls, size, fields in layouts:
        rn = rust_name(cls)
        out.append(f"static {rn}_FIELDS: &[FieldDef] = &[")
        for f in fields:
            name = f["name"].replace("\\", "\\\\").replace('"', '\\"')
            out.append(f'    FieldDef {{ off: {f["off"]}, size: {f["size"]}, name: "{name}" }},')
        out.append("];")
        out.append(
            f'static {rn}: ClassLayout = ClassLayout {{ name: "{cls}", '
            f'sizeof: {size}, fields: {rn}_FIELDS }};')
        out.append("")
    out.append("/// All generated layouts, in declaration order.")
    out.append("pub static ALL: &[&ClassLayout] = &[")
    for cls, _, _ in layouts:
        out.append(f"    &{rust_name(cls)},")
    out.append("];")
    out.append("")
    out.append("/// Look up a class layout by exact retail class name.")
    out.append("pub fn lookup(name: &str) -> Option<&'static ClassLayout> {")
    out.append("    ALL.iter().copied().find(|c| c.name == name)")
    out.append("}")
    out.append("")
    out.append("/// Fields of `layout` covering byte range `start..end` (relative to")
    out.append("/// the class image). Returns the overlapping field names, deduplicated.")
    out.append("pub fn fields_covering(layout: &ClassLayout, start: usize, end: usize) -> Vec<&'static str> {")
    out.append("    let mut v: Vec<&'static str> = layout.fields.iter()")
    out.append("        .filter(|f| (f.off as usize) < end && (f.off as usize + f.size as usize) > start)")
    out.append("        .map(|f| f.name)")
    out.append("        .collect();")
    out.append("    v.dedup();")
    out.append("    v")
    out.append("}")
    out.append("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write("\n".join(out))
    total = sum(len(f) for _, _, f in layouts)
    print(f"wrote {OUT}: {len(layouts)} classes, {total} fields")


if __name__ == "__main__":
    main()
