//! `ScenarioFuncSet` — the 842 builtins that touch the game, and the first 21 of them.
//!
//! [`crate::builtins`] covers the four *utility* function sets, which need no simulation.
//! This module is the other side of that seam: builtins registered by `ScenarioFuncSet`
//! (`OP_CALL_GAME` indices 31..872), where the handler reads `Game`, `Leaders`, the object
//! bands or the script engine's own `ScenarioData`.
//!
//! # Why these twenty-one
//!
//! `ron-data/bhs-corpus/scenario/scriptlibrary/general_powers.bhs` — the second script
//! retail runs at tick step 4, made loadable by the script-load-path lane — calls exactly
//! **seven** builtins: `time_sec`, `set_timer`, `timer_expired`, `object_type_selected`,
//! `find_unit`, `length` and `bubble_text_obj`. `length` was already implemented. The
//! other six are here, so that script is now executable rather than merely loadable.
//!
//! Around them sit three cheap neighbours and the twelve zero-argument rules gates the
//! shipped AI opening book branches on:
//!
//! | index | name | handler | what it reads |
//! |---|---|---|---|
//! | 77 | `set_timer` | `0x009e4bc0` | `ScenarioData::timers`, `Game::tick` |
//! | 78 | `stop_timer` | `0x009e4c10` | `ScenarioData::timers` |
//! | 79 | `timer_expired` | `0x009e4c80` | `ScenarioData::timers`, `Game::tick` |
//! | 94 | `get_is_no_nation_powers` | `0x009e5230` | `GameInfo::flags` bit 2 |
//! | 95 | `get_rush_rules` | `0x009e5240` | `GameInfo::rush_rules` |
//! | 96..105 | `is_victory_*` | `0x009e5250`..`0x009e52e0` | `GameInfo::victory` |
//! | 147 | `is_conquest_scenario` | `0x009e6040` | `Game::semaphore` bit 17 |
//! | 298 | `time_sec` | `0x009ead40` | `Game::tick` |
//! | 311 | `find_unit` | `0x009ebe10` | `Units::lists`, `Leaders`, a static cursor |
//! | 390 | `object_type_selected` | `0x009f04e0` | the local selection group |
//! | 392 | `num_objects_selected` | `0x009f06f0` | the local selection group |
//! | 783 | `bubble_text_obj` | `0x009ff550` | the object band, `MessageWin` |
//!
//! # Where the boundary is, and why it is where it is
//!
//! Every handler above was read at the instruction level (see
//! `docs/mechanics/bhs-scenario-builtins.md` for the per-address derivation). The *guard
//! logic* — the 1-based `who`, the `who - 1 > 7` unsigned bound, the `Leaders` flag pair,
//! the empty-string cases, the `-1` / `0` / `1` return trichotomy, the static search cursor
//! — is the majority of each body and lives here, executed. What a handler reads out of
//! the simulation is a [`Host`] method that *names the retail address and field it stands
//! for*. A host that cannot answer yields [`HostError::Unimplemented`] and the VM stops;
//! nothing in this module substitutes a plausible number.
//!
//! `ScenarioData::timers` is different in kind: it is script-engine state, not simulation
//! state, so [`ScriptTimers`] is a complete reimplementation of the retail container and
//! runs entirely here.
//!
//! # Fidelity
//!
//! Tier C throughout. Static analysis of `ron-bin/riseofnations.exe` (PE32 i386, image
//! base `0x00400000`) with Capstone plus the matching private PDB. Nothing here has been
//! executed against retail. Not verified, not proven, not a refinement.

