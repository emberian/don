// String equality, as `String::operator==` performs it
// ---------------------------------------------------------------------------

/// `String::operator==` `0x00a1f140`, restricted to the subdomain it can be reproduced on.
///
/// The retail body, read at `0x00a1f140`:
///
/// 1. `curr_len` (`String+8`, a `short` count of UTF-16 code units) must match, else false;
/// 2. if **both** operands have `flags & 2` — hashes generated by
///    `String::generate_hashes` `0x00a1ee60` — it returns `hash2 == hash2`
///    (`String+0x10`) and nothing else. A hash collision reads as equal;
/// 3. otherwise it forwards to the CRT `_wcsicmp` (import `0x00ac5640`), i.e. a
///    **case-insensitive** compare.
///
/// Step 2 is a deliberate hole here. Reproducing it needs `String::generate_hash`
/// `0x00a1b6b0` and its 50-word table at `0x00b14500`, *and* a model of which `String`s
/// carry hashes — and `Value::Str` is an `Rc<String>` with no flags word, so don-bhs
/// cannot represent that state at all. Documented, not approximated.
///
/// Step 3 is reproduced for ASCII only. MSVCRT `towlower` in the startup locale folds
/// `A..Z` and nothing else; asserting that for U+0080.. would be a guess, so a pair that
/// is not byte-identical and is not wholly ASCII **poisons**.
pub fn string_eq(a: &str, b: &str) -> Result<bool, HostError> {
    // `curr_len` is a UTF-16 code-unit count, so this is the retail length test.
    if a.encode_utf16().count() != b.encode_utf16().count() {
        return Ok(false);
    }
    if a == b {
        return Ok(true);
    }
    if !a.is_ascii() || !b.is_ascii() {
        // Two different non-ASCII strings of equal length: folding is undetermined.
        return Err(HostError::Unimplemented);
    }
    Ok(a.eq_ignore_ascii_case(b))
}

