/// One live timer: a name and the `Game::tick` value at which it comes due.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Timer {
    /// `LLNode<String,int>+0x08`.
    pub name: String,
    /// `LLNode<String,int>+0x1c` — an absolute `Game::tick`, not a duration.
    pub expires_at: i32,
}

/// `ScenarioData::timers` `0x00ed6650` — a `LinkListBase<String,int,LLNode<String,int>>`.
///
/// Layout as read from the globals the container's methods address directly: [measured]
///
/// ```text
/// +0x00  String  current_key      // 0x00ed6650, a 20-byte String mirror
/// +0x14  int     current_value    // 0x00ed6664
/// +0x18  LLNode* current          // 0x00ed6668
/// +0x1c  int     count            // 0x00ed666c
/// +0x20  LLNode* head             // 0x00ed6670
/// ```
///
/// The list is **circular and doubly linked** (`LLNode+0` next, `+4` prev) and
/// `ordered_insert` `0x004d2120` keeps it sorted **ascending by expiry**, so `head` is
/// always the soonest timer. The `current` cursor is not a convenience: `check`
/// `0x00a04b80` reads the expiry through `current_value`, which `seek` `0x004d2340` sets
/// as a side effect, and `remove_current` `0x004c9060` advances it.
///
/// This is script-engine state, not simulation state, so it is implemented in full here.
/// The `Vec` keeps the retail order exactly, with element 0 being `head`.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ScriptTimers {
    entries: Vec<Timer>,
    current: Option<usize>,
    /// Set when `add_timer` refused at the cap, mirroring `Error::report` `0x00a2e550`.
    pub overflowed: u32,
}

impl ScriptTimers {
    /// `cmp dword ptr [0x00ed666c], 0x64` at `ScriptTimers::add_timer+0x1b` — a hundred
    /// live timers is the hard cap, and the hundred-and-first is an `Error::report`, not a
    /// silent drop. [measured, `0x00a049fb`]
    pub const MAX_TIMERS: usize = 100;

    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    /// `LinkListBase::count` (`0x00ed666c`).
    pub fn len(&self) -> usize {
        self.entries.len()
    }

    /// The list in retail order: ascending expiry, `head` first.
    pub fn iter(&self) -> impl Iterator<Item = &Timer> {
        self.entries.iter()
    }

    /// The `current` cursor's entry, i.e. the `current_key` / `current_value` mirror.
    pub fn current(&self) -> Option<&Timer> {
        self.current.and_then(|i| self.entries.get(i))
    }

    /// `LinkListBase::seek` `0x004d2340`. On a hit it moves `current` and returns true; on
    /// a miss it returns false and **leaves `current` where it was** — retail does not
    /// clear the cursor on a failed seek.
    fn seek(&mut self, name: &str) -> Result<bool, HostError> {
        for i in 0..self.entries.len() {
            if string_eq(&self.entries[i].name, name)? {
                self.current = Some(i);
                return Ok(true);
            }
        }
        Ok(false)
    }

    /// `LinkListBase::ordered_insert` `0x004d2120`.
    ///
    /// The walk at `0x004d21a7..0x004d21c2` advances while `new > node->value` and inserts
    /// *before* the first node whose value is `>=` the new one — so equal expiries put the
    /// newest first. A value greater than every node's inserts before `head`, i.e. at the
    /// tail of the circular list, without moving `head`. `current` becomes the new node.
    fn ordered_insert(&mut self, name: &str, expires_at: i32) {
        let at = self
            .entries
            .iter()
            .position(|e| e.expires_at >= expires_at)
            .unwrap_or(self.entries.len());
        self.entries.insert(
            at,
            Timer {
                name: name.to_string(),
                expires_at,
            },
        );
        self.current = Some(at);
    }

    /// `LinkListBase::remove_current` `0x004c9060`: drop `current` and advance the cursor
    /// to its successor, wrapping to `head`. A one-element list clears the whole container
    /// including the cursor.
    fn remove_current(&mut self) {
        let Some(i) = self.current else { return };
        if i >= self.entries.len() {
            return;
        }
        self.entries.remove(i);
        self.current = if self.entries.is_empty() {
            None
        } else {
            Some(i % self.entries.len())
        };
    }

    /// `LinkListBase::remove` `0x004d2230`. Returns whether a node was unlinked.
    ///
    /// Removing a node that is *not* `current` leaves the cursor on the same node — which
    /// in this representation means fixing up its index.
    fn remove(&mut self, name: &str) -> Result<bool, HostError> {
        let mut found = None;
        for i in 0..self.entries.len() {
            if string_eq(&self.entries[i].name, name)? {
                found = Some(i);
                break;
            }
        }
        let Some(i) = found else { return Ok(false) };
        let cur = self.current;
        self.entries.remove(i);
        self.current = if self.entries.is_empty() {
            None
        } else {
            match cur {
                // The cursor node itself went: retail advanced it to the successor.
                Some(c) if c == i => Some(i % self.entries.len()),
                Some(c) if c > i => Some(c - 1),
                other => other.map(|c| c.min(self.entries.len() - 1)),
            }
        };
        Ok(true)
    }

    /// `ScriptTimers::add_timer` `0x00a049e0`.
    ///
    /// `1` on success, `-1` at the cap. An existing timer of the same name is removed
    /// first (`seek` then `remove_current`), so this is a map insert, not a multimap one.
    pub fn add_timer(&mut self, name: &str, expires_at: i32) -> Result<i32, HostError> {
        if self.entries.len() >= Self::MAX_TIMERS {
            self.overflowed = self.overflowed.saturating_add(1);
            return Ok(-1);
        }
        if self.seek(name)? {
            self.remove_current();
        }
        self.ordered_insert(name, expires_at);
        Ok(1)
    }

    /// `ScriptTimers::remove_timer` / the `stop_timer` path: `LinkListBase::remove`.
    pub fn remove_timer(&mut self, name: &str) -> Result<bool, HostError> {
        self.remove(name)
    }

    /// `ScriptTimers::check` `0x00a04b80`.
    ///
    /// `-1` no such timer, `0` not due yet, `1` due — and a due timer is **consumed**
    /// (`remove_current` at `0x00a04bcd`), which is why the shipped scripts re-arm inside
    /// the `if (timer_expired(...))` body.
    ///
    /// The comparison is `now >= expiry` on signed 32-bit `Game::tick`.
    pub fn check(&mut self, name: &str, now: i32) -> Result<i32, HostError> {
        if !self.seek(name)? {
            return Ok(-1);
        }
        let due = self.current().map(|t| t.expires_at).unwrap_or(i32::MAX);
        if now >= due {
            self.remove_current();
            Ok(1)
        } else {
            Ok(0)
        }
    }
}

