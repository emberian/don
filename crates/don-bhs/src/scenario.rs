/// The `Game` scalars the twelve zero-argument gates read, in one place.
///
/// This is an *image*, not a simulation: a caller fills it from wherever it knows the
/// truth (a save game, a scenario file, `don-sim`). Every field names the retail address
/// it stands for so a bridge cannot connect the wrong one.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct GameImage {
    /// `Game::tick` `Game+0x560`, game seconds.
    pub tick: i32,
    /// `GameInfo::flags` `Game+0x20` (`GameInfo+0x14`).
    pub info_flags: u32,
    /// `GameInfo::rush_rules` `Game+0x32` (`GameInfo+0x26`), a `RushRulesIndex`.
    pub rush_rules: u8,
    /// `GameInfo::victory` `Game+0x38` (`GameInfo+0x2c`), a `VictoryIndex`.
    pub victory: u8,
    /// `Game::semaphore` `Game+0x814`, the 32 bit-bytes from `Game+0x820`.
    pub semaphore: [u8; 32],
}

impl GameImage {
    pub fn semaphore_bit(&self, bit: u32) -> bool {
        let b = (bit / 8) as usize;
        b < self.semaphore.len() && self.semaphore[b] & (1 << (bit % 8)) != 0
    }

    pub fn set_semaphore_bit(&mut self, bit: u32, on: bool) {
        let b = (bit / 8) as usize;
        if b >= self.semaphore.len() {
            return;
        }
        let m = 1u8 << (bit % 8);
        if on {
            self.semaphore[b] |= m;
        } else {
            self.semaphore[b] &= !m;
        }
    }
}

/// One object as the scenario builtins interrogate it.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct ObjectImage {
    pub probe: ObjectProbe,
    /// The index the object's `ptype` occupies in the 806-entry type array — what
    /// `SubObject::is(type_index, 0)` answers against.
    pub type_index: i32,
    /// `SubObjectData::x_internal` / `y_internal` **as stored**, i.e. already XORed with
    /// [`object_band::POSITION_XOR`].
    pub x_internal: i32,
    pub y_internal: i32,
}

/// An explicit image of everything outside `ScenarioData` that the cohort reads.
///
/// It exists so a shipped script can be *run* without `don-sim`, and so the guard logic
/// above is exercised by tests rather than asserted about. It is a fixture, not a model of
/// the simulation: nothing here advances, decays or interacts.
///
/// # One band, two retail symbols
///
/// The `find_unit` scan indexes `Units::lists[who0]` (`0x00c0aec0`, stride `0x1c`) while
/// `valid_object_o` and `object_type_selected` index `Objects::lists[who0]`
/// (`[0x00c0618c] + 0x14 + who0*0x1c`). Those are two distinct symbols and this lane did
/// **not** prove they alias. What is established is that they must share a slot space:
/// `general_powers.bhs` assigns `o = find_unit(1, "Alexander")` — a `Units::lists` band
/// index — and passes it straight to `bubble_text_obj`, which resolves it through
/// `Objects::lists`. So the image keeps one map keyed by `(who0, handle)` and answers both
/// accessors from it. A host that can distinguish the two arrays should say so rather than
/// inherit this simplification.
#[derive(Debug, Clone, Default)]
pub struct ScenarioWorldImage {
    /// `Leaders` `0x00e3a390` stride `0x6eec`, first dword, indexed by `who - 1`.
    pub leader_flags: [u32; 8],
    /// `TypeData+0x60` for each of the 806 type records, in array order. Comparison is
    /// [`string_eq`].
    pub type_names: Vec<String>,
    /// Which of those indices `TypeData::is_unit_type` accepts. The devirtualised form the
    /// binary inlines at `0x009ebe5d` is `0x32 <= TypeData+4 < 0x19e`; a host that knows
    /// the type numbers can populate this from that range instead of by name.
    pub unit_type_indices: std::collections::BTreeSet<i32>,
    /// The per-owner object slots, keyed `(who0, handle)`. Absent means an empty slot,
    /// which every predicate reads as not-alive.
    pub objects: BTreeMap<(i32, i32), ObjectImage>,
    /// `Objects+0x15c+who0*4` — the band high-water `find_unit`'s scan wraps against. It
    /// is a count, not a maximum handle, and it is what makes the scan terminate.
    pub unit_band_count: BTreeMap<i32, i32>,
    /// `GroupData+0x4a` of the local console's select group.
    pub selection_owner: i32,
    /// `GroupData+0x8cc`, the `short[]` member handles.
    pub selection: Vec<i32>,
    /// `Console+0x298`.
    pub local_display_player: i32,
}

impl ScenarioWorldImage {
    /// Place one object at `(who0, handle)` and widen the band high-water to cover it.
    pub fn put_object(&mut self, who0: i32, handle: i32, o: ObjectImage) -> &mut Self {
        self.objects.insert((who0, handle), o);
        let e = self.unit_band_count.entry(who0).or_insert(0);
        *e = (*e).max(handle + 1);
        self
    }
}

/// A [`Host`] that implements the utility function sets, the [`ScriptTimers`] subsystem,
/// and the twenty-one `ScenarioFuncSet` entries in this module — the rest poison.
///
/// This is the host a shipped scenario script can actually run on.
#[derive(Default)]
pub struct ScenarioHost {
    /// The four utility `FuncSet`s, including the shared `GameAccess::game_random` stream.
    pub util: crate::builtins::UtilHost,
    /// `ScenarioData::timers` `0x00ed6650`.
    pub timers: ScriptTimers,
    /// `Game` scalars.
    pub game: GameImage,
    /// Everything else the cohort reads. `None` means "this host does not model the
    /// world", and every builtin that needs it poisons rather than answering.
    pub world: Option<ScenarioWorldImage>,
    /// `[0x00cc2214]`, the `find_unit` search cursor.
    pub find_cursor: i32,
    /// Everything `bubble_text_obj` handed to `MessageWin::add_bubble_message`, in order:
    /// `(text, x, y, display_player)`.
    pub bubbles: Vec<(String, i32, i32, i32)>,
}

impl ScenarioHost {
    pub fn new() -> ScenarioHost {
        ScenarioHost::default()
    }

    fn world(&self) -> Result<&ScenarioWorldImage, HostError> {
        self.world.as_ref().ok_or(HostError::Unimplemented)
    }
}

impl Host for ScenarioHost {
    fn call(&mut self, decl: &BuiltinDecl, args: &[Value]) -> HostResult {
        if let Some(r) = crate::builtins::call_util(self, decl, args) {
            return r;
        }
        if let Some(r) = call_scenario(self, decl, args) {
            return r;
        }
        Err(HostError::Unimplemented)
    }

    fn game_random(&mut self, lo: i32, hi: i32) -> Result<i32, HostError> {
        self.util.game_random(lo, hi)
    }
    fn game_random_step(&mut self) -> Result<u32, HostError> {
        self.util.game_random_step()
    }
    fn game_random_seed(&self) -> Result<u32, HostError> {
        self.util.game_random_seed()
    }
    fn set_game_random_seed(&mut self, s: u32) -> Result<(), HostError> {
        self.util.set_game_random_seed(s)
    }
    fn script_print(&mut self, s: &str, newline: bool) -> Result<(), HostError> {
        self.util.script_print(s, newline)
    }

    fn game_seconds(&mut self) -> Result<i32, HostError> {
        Ok(self.game.tick)
    }
    fn game_info_flags(&mut self) -> Result<u32, HostError> {
        Ok(self.game.info_flags)
    }
    fn game_info_rush_rules(&mut self) -> Result<u8, HostError> {
        Ok(self.game.rush_rules)
    }
    fn game_info_victory(&mut self) -> Result<u8, HostError> {
        Ok(self.game.victory)
    }
    fn game_semaphore_bit(&mut self, bit: u32) -> Result<bool, HostError> {
        Ok(self.game.semaphore_bit(bit))
    }
    fn script_timers(&mut self) -> Result<&mut ScriptTimers, HostError> {
        Ok(&mut self.timers)
    }

    fn find_unit_cursor(&mut self) -> Result<i32, HostError> {
        Ok(self.find_cursor)
    }
    fn set_find_unit_cursor(&mut self, v: i32) -> Result<(), HostError> {
        self.find_cursor = v;
        Ok(())
    }

    fn leader_flags(&mut self, who0: i32) -> Result<u32, HostError> {
        let w = self.world()?;
        w.leader_flags
            .get(who0 as usize)
            .copied()
            .ok_or(HostError::BadArgs("leader_flags: who0 out of 0..8"))
    }

    fn type_index_by_name(&mut self, name: &str) -> Result<i32, HostError> {
        let names = self.world()?.type_names.clone();
        for (i, n) in names.iter().enumerate() {
            if i as i32 >= object_band::TYPE_COUNT {
                break;
            }
            if string_eq(n, name)? {
                return Ok(i as i32);
            }
        }
        Ok(-1)
    }

    fn type_is_unit_type(&mut self, type_index: i32) -> Result<bool, HostError> {
        Ok(self.world()?.unit_type_indices.contains(&type_index))
    }

    fn unit_band_count(&mut self, who0: i32) -> Result<i32, HostError> {
        Ok(self
            .world()?
            .unit_band_count
            .get(&who0)
            .copied()
            .unwrap_or(0))
    }

    fn unit_band_probe(&mut self, who0: i32, idx: i32) -> Result<ObjectProbe, HostError> {
        self.object_band_probe(who0, idx)
    }

    fn unit_band_is_type(
        &mut self,
        who0: i32,
        idx: i32,
        type_index: i32,
    ) -> Result<bool, HostError> {
        self.object_band_is_type(who0, idx, type_index)
    }

    fn object_band_probe(&mut self, who0: i32, o: i32) -> Result<ObjectProbe, HostError> {
        Ok(self
            .world()?
            .objects
            .get(&(who0, o))
            .map(|x| x.probe)
            .unwrap_or_default())
    }

    fn object_band_is_type(
        &mut self,
        who0: i32,
        o: i32,
        type_index: i32,
    ) -> Result<bool, HostError> {
        Ok(self
            .world()?
            .objects
            .get(&(who0, o))
            .map(|x| x.type_index == type_index)
            .unwrap_or(false))
    }

    fn object_band_position_internal(
        &mut self,
        who0: i32,
        o: i32,
    ) -> Result<(i32, i32), HostError> {
        self.world()?
            .objects
            .get(&(who0, o))
            .map(|x| (x.x_internal, x.y_internal))
            .ok_or(HostError::BadArgs("object_band_position: no such handle"))
    }

    fn selection_group_owner(&mut self) -> Result<i32, HostError> {
        Ok(self.world()?.selection_owner)
    }

    fn selection_group_members(&mut self) -> Result<Vec<i32>, HostError> {
        Ok(self.world()?.selection.clone())
    }

    fn local_display_player(&mut self) -> Result<i32, HostError> {
        Ok(self.world()?.local_display_player)
    }

    fn add_bubble_message(
        &mut self,
        text: &str,
        x: i32,
        y: i32,
        who: i32,
    ) -> Result<(), HostError> {
        self.bubbles.push((text.to_string(), x, y, who));
        Ok(())
    }
}
