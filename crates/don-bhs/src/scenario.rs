fn arg(args: &[Value], i: usize) -> Value {
    args.get(i).cloned().unwrap_or(Value::Null)
}

fn str_arg(args: &[Value], i: usize, what: &'static str) -> Result<String, HostError> {
    arg(args, i)
        .as_string()
        .map_err(|_| HostError::BadArgs(what))
}

/// Dispatch one `ScenarioFuncSet` builtin.
///
/// Returns `None` when `decl` is not one of the indices this module covers, so a host can
/// chain it after [`crate::builtins::call_util`] and fall through to its own table:
///
/// ```ignore
/// fn call(&mut self, decl: &BuiltinDecl, args: &[Value]) -> HostResult {
///     if let Some(r) = don_bhs::builtins::call_util(self, decl, args) { return r; }
///     if let Some(r) = don_bhs::scenario::call_scenario(self, decl, args) { return r; }
///     Err(HostError::Unimplemented)
/// }
/// ```
pub fn call_scenario<H: Host + ?Sized>(
    host: &mut H,
    decl: &BuiltinDecl,
    args: &[Value],
) -> Option<HostResult> {
    if !implemented_indices().contains(&decl.index) {
        return None;
    }
    Some(dispatch(host, decl, args))
}

fn dispatch<H: Host + ?Sized>(host: &mut H, decl: &BuiltinDecl, args: &[Value]) -> HostResult {
    match decl.index {
        // ---- ScriptTimers ----------------------------------------------------
        //
        // set_timer(timer_id, seconds) `0x009e4bc0`:
        //   msg = timer_id                                       0x009e4bcd
        //   if (seconds <= 0)          return -1                 0x009e4bd9
        //   if (timer_id.curr_len == 0) return -1                0x009e4be0
        //   tail-jmp add_timer(msg, Game::tick + seconds)        0x009e4bf4
        // Both refusals are -1 and the order is seconds-then-length, so
        // `set_timer("", 0)` and `set_timer("", 5)` are the same answer for
        // different reasons.
        77 => {
            let name = str_arg(args, 0, "set_timer: timer_id is not a string")?;
            let seconds = arg(args, 1).as_int();
            if seconds <= 0 {
                return Ok(Value::Int(-1));
            }
            if name.is_empty() {
                return Ok(Value::Int(-1));
            }
            // `add eax, ecx` on two ints: wrapping, not saturating.
            let expires_at = host.game_seconds()?.wrapping_add(seconds);
            let t = host.script_timers()?;
            Ok(Value::Int(t.add_timer(&name, expires_at)?))
        }
        // stop_timer(timer_id) `0x009e4c10`: `remove(msg) ? 1 : -1`. Note there is no
        // empty-name guard here, unlike set_timer — `stop_timer("")` really does search
        // for a timer named "".
        78 => {
            let name = str_arg(args, 0, "stop_timer: timer_id is not a string")?;
            let t = host.script_timers()?;
            Ok(Value::Int(if t.remove_timer(&name)? { 1 } else { -1 }))
        }
        // timer_expired(timer_id) `0x009e4c80`: `check(msg, Game::tick)`.
        //
        // `re/decomp-all/009e4c80.c` types this `void` and drops the second argument
        // entirely; the tail call at `0x009e4c9c` passes `Game+0x560` and returns
        // `ScriptTimers::check`'s EAX. The declaration in `schema/bhs-builtins.json`
        // agrees with the disassembly: `int`.
        79 => {
            let name = str_arg(args, 0, "timer_expired: timer_id is not a string")?;
            let now = host.game_seconds()?;
            let t = host.script_timers()?;
            Ok(Value::Int(t.check(&name, now)?))
        }

        // ---- GameInfo scalars ------------------------------------------------
        // get_is_no_nation_powers() `0x009e5230`: `(*(u8*)(Game+0x20) >> 2) & 1`.
        // `Game+0x20` is `GameInfo::flags` (`GameInfo` is `Game+0x0C`, `flags` is +0x14),
        // read as a byte, so only bits 0..7 are reachable from here.
        94 => Ok(Value::Int(((host.game_info_flags()? >> 2) & 1) as i32)),
        // get_rush_rules() `0x009e5240`: `movzx eax, byte [Game+0x32]` — GameInfo+0x26,
        // a `RushRulesIndex` (`RUSH_STANDARD`=0 .. `RUSH_30_MINUTES`=14).
        95 => Ok(Value::Int(host.game_info_rush_rules()? as i32)),
        // is_victory_*() `0x009e5250`..`0x009e52e0`: `sete` on `GameInfo::victory`.
        96..=105 => {
            let want = match decl.index {
                96 => victory::STANDARD,
                97 => victory::CONQUEST,
                98 => victory::ECONOMIC,
                99 => victory::MUSICAL_CHAIRS,
                100 => victory::SCORE,
                101 => victory::SUDDEN_DEATH,
                102 => victory::TECH_RACE,
                103 => victory::TERRITORY,
                104 => victory::TIME_LIMIT,
                _ => victory::WONDER,
            };
            Ok(Value::Int((host.game_info_victory()? == want) as i32))
        }
        // is_conquest_scenario() `0x009e6040`: `(*(u8*)(Game+0x822) >> 1) & 1`.
        147 => Ok(Value::Int(
            host.game_semaphore_bit(semaphore_bit::CONQUEST_SCENARIO)? as i32,
        )),
        // time_sec() `0x009ead40` — twelve bytes: `Game::tick` (`Game+0x560`) verbatim.
        // The PDB calls the field `tick`; `docs/mechanics/victory-score.md` already
        // establishes it counts game seconds, which is what makes `set_timer`'s
        // `tick + seconds` type-correct.
        298 => Ok(Value::Int(host.game_seconds()?)),

        // ---- find_unit -------------------------------------------------------
        311 => find_unit(host, args),
        // ---- the local selection group ---------------------------------------
        390 => object_type_selected(host, args),
        392 => num_objects_selected(host, args),
        // ---- presentation ----------------------------------------------------
        783 => bubble_text_obj(host, args),

        _ => Err(HostError::Unimplemented),
    }
}

/// `who` is 1-based in every scenario builtin that takes one; the handler's first act is
/// `dec`, and the bound is then an **unsigned** `> 7`, so `who = 0` becomes `0xffffffff`
/// and is refused. [measured: `0x009ebe22`/`0x009ebe75`, `0x009f04f3`/`0x009f054d`,
/// `0x009f06f8`, `0x009ff55c`]
fn who_zero_based(v: i32) -> Option<i32> {
    let who0 = v.wrapping_sub(1);
    (0..=7).contains(&who0).then_some(who0)
}

/// `ScenarioFuncSet::find_unit` builtin 311, `0x009ebe10`, and the scan it calls,
/// `ScenarioFuncSet::find_unit` `0x009e2850`.
///
/// The outer handler is a cursor plus five refusals; the inner is a wrapping scan of the
/// owner's `Units::lists` band (`0x00c0aec0`, stride `0x1c` per owner, count at
/// `Objects+0x15c+who0*4`).
fn find_unit<H: Host + ?Sized>(host: &mut H, args: &[Value]) -> HostResult {
    let who_raw = arg(args, 0).as_int();
    let type_name = str_arg(args, 1, "find_unit: unit_type is not a string")?;

    // `[0x00cc2214]`, a file-static search cursor clamped at zero and read *before* any
    // refusal path. It is not per-type and not per-player: consecutive find_unit calls in
    // one script share it, which is why general_powers.bhs walking thirteen leaders in one
    // frame does not restart from object 0 each time.
    let cursor = host.find_unit_cursor()?.max(0);
    host.set_find_unit_cursor(cursor)?;

    let type_index = if type_name.is_empty() {
        // An empty unit_type is "any unit", encoded as -1 — the `or edi, -1` at
        // `0x009ebe9a`, *not* a refusal.
        -1
    } else {
        let ti = host.type_index_by_name(&type_name)?;
        if ti < 0 {
            return Ok(Value::Int(-1));
        }
        if !host.type_is_unit_type(ti)? {
            return Ok(Value::Int(-1));
        }
        ti
    };

    let Some(who0) = who_zero_based(who_raw) else {
        return Ok(Value::Int(-1));
    };
    let flags = host.leader_flags(who0)?;
    if flags & leader_flag::VALID == 0 || flags & leader_flag::PRESENT == 0 {
        return Ok(Value::Int(-1));
    }

    let found = find_unit_scan(host, who0, type_index, cursor, find_unit_mode::ON_MAP)?;
    if found < 0 {
        return Ok(Value::Int(-1));
    }
    host.set_find_unit_cursor(found)?;
    Ok(Value::Int(found))
}

/// `ScenarioFuncSet::find_unit(type_index, start, mode)` `0x009e2850`, `who0` in `ECX`.
///
/// ```text
///   n = Objects+0x15c+who0*4                       // the band's high-water count
///   if (start >= n || start < 0) start = 0         // 0x009e286b..0x009e2874
///   i = start + 1                                  // the scan begins *after* start
///   do {
///     idx = (i < n) ? i : 0                        // 0x009e2897 cmovl
///     ...
///     i = idx + 1
///   } while (i != start + 1)
///   return -1
/// ```
///
/// Two facts worth not re-deriving: the scan starts at `start + 1`, so a repeated call
/// with an unchanged cursor finds the *next* match rather than the same object; and the
/// wrap sentinel is compared against `start + 1`, so index `start` itself is the last
/// candidate examined, not a skipped one.
pub fn find_unit_scan<H: Host + ?Sized>(
    host: &mut H,
    who0: i32,
    type_index: i32,
    start: i32,
    mode: i32,
) -> Result<i32, HostError> {
    let n = host.unit_band_count(who0)?;
    if n <= 0 {
        // With n <= 0 the cmovl never fires, idx is 0 forever and `i` never returns to
        // `first`; retail would spin. Refuse rather than reproduce a hang.
        return Err(HostError::BadArgs(
            "find_unit: empty unit band; retail 0x009e2850 does not terminate here",
        ));
    }
    let start = if start >= n || start < 0 { 0 } else { start };
    let first = start + 1;
    let mut i = first;
    loop {
        let idx = if i < n { i } else { 0 };
        let p = host.unit_band_probe(who0, idx)?;
        // Three gates in the order the body applies them, each short-circuiting the next:
        // the raw liveness bit and `ObjectData::is_captain` (`0x009e28a7`, `0x009e28b3`);
        // the type filter, skipped entirely when `type_index < 0` (`0x009e28c1`); then the
        // mode predicate (`0x009e28e0`).
        let mut accept = p.alive && p.is_captain;
        if accept && type_index >= 0 {
            accept = host.unit_band_is_type(who0, idx, type_index)?;
        }
        if accept {
            accept = match mode {
                find_unit_mode::ANY => true,
                find_unit_mode::ON_MAP => p.is_valid_unit && p.is_on_map,
                find_unit_mode::OFF_MAP_ACTIVE => !p.is_on_map && p.is_active,
                // The `sub/je` chain falls through to "reject" for any other value.
                _ => false,
            };
        }
        if accept {
            return Ok(idx);
        }
        i = idx + 1;
        if i == first {
            return Ok(-1);
        }
    }
}

/// `ScenarioFuncSet::object_type_selected` builtin 390, `0x009f04e0`.
///
/// Answers "does player `who` have an object of this type selected **right now**". The
/// selection it reads is `[0x00e8d444] + Console+0x2a0 * 0x9f0`, the *local* console's
/// select group, and the handler refuses unless that group's owner byte (`GroupData+0x4a`)
/// equals `who - 1`. That makes this builtin a function of local UI state, not of shared
/// simulation state — a script branching on it is not reproducible from a replay alone.
fn object_type_selected<H: Host + ?Sized>(host: &mut H, args: &[Value]) -> HostResult {
    let who_raw = arg(args, 0).as_int();
    let type_name = str_arg(args, 1, "object_type_selected: object_type is not a string")?;
    if type_name.is_empty() {
        return Ok(Value::Int(-1));
    }
    // `String::generate_hashes` at `0x009f0501` is a comparison accelerator, not a
    // semantic step; see `string_eq`.
    let type_index = host.type_index_by_name(&type_name)?;
    if type_index < 0 {
        return Ok(Value::Int(-1));
    }
    if host.game_semaphore_bit(semaphore_bit::SELECTION_BLOCKED)? {
        return Ok(Value::Int(-1));
    }
    let Some(who0) = who_zero_based(who_raw) else {
        return Ok(Value::Int(-1));
    };
    // Bit 0 only. `num_objects_selected`, four instructions away, also requires bit 1.
    if host.leader_flags(who0)? & leader_flag::VALID == 0 {
        return Ok(Value::Int(-1));
    }
    if host.selection_group_owner()? != who0 {
        return Ok(Value::Int(0));
    }
    let members = host.selection_group_members()?;
    if members.is_empty() {
        return Ok(Value::Int(0));
    }
    for o in members {
        if !host.object_band_is_type(who0, o, type_index)? {
            continue;
        }
        let p = host.object_band_probe(who0, o)?;
        // `0x009f0617`: a matching non-building answers yes immediately; a matching
        // building answers with `is_active`, and **returns** either way rather than
        // continuing the scan. A selection holding an unfinished Barracks and a finished
        // one therefore answers on whichever comes first in the group.
        return Ok(Value::Int(if !p.is_build { 1 } else { p.is_active as i32 }));
    }
    Ok(Value::Int(0))
}

/// `ScenarioFuncSet::num_objects_selected` builtin 392, `0x009f06f0`.
///
/// Same five refusals as [`object_type_selected`] except that it also requires
/// [`leader_flag::PRESENT`], then returns `GroupData::get_num_cap_const` `0x0070f960` —
/// the count of members that are still alive and `ObjectData::is_captain`, which is *not*
/// the same as the group's raw `+0xc` count.
fn num_objects_selected<H: Host + ?Sized>(host: &mut H, args: &[Value]) -> HostResult {
    let Some(who0) = who_zero_based(arg(args, 0).as_int()) else {
        return Ok(Value::Int(-1));
    };
    let flags = host.leader_flags(who0)?;
    if flags & leader_flag::VALID == 0 || flags & leader_flag::PRESENT == 0 {
        return Ok(Value::Int(-1));
    }
    if host.game_semaphore_bit(semaphore_bit::SELECTION_BLOCKED)? {
        return Ok(Value::Int(-1));
    }
    if host.selection_group_owner()? != who0 {
        return Ok(Value::Int(0));
    }
    // The band `GroupData::get_num_cap_const` indexes is `[0x00c0ab84 + owner*0x1c]`,
    // which is a *different* base from `Objects` (`0x00c0618c`) and from `Units::lists`
    // (`0x00c0aec0`) and has not been identified. The loop itself is
    //   n = group->count; for each member, if !(alive && is_captain) n--
    // and it is reproduced here over the object band, which is the same predicate on the
    // same handles. If a host's two bands can disagree, that is the divergence to look at.
    let members = host.selection_group_members()?;
    let mut n = members.len() as i32;
    for o in members {
        let p = host.object_band_probe(who0, o)?;
        if !(p.alive && p.is_captain) {
            n -= 1;
        }
    }
    Ok(Value::Int(n))
}

/// `ScenarioFuncSet::bubble_text_obj` builtin 783, `0x009ff550`.
///
/// `valid_object_o` `0x009e32a0` inline, then `MessageWin::add_bubble_message`
/// `0x007e7e20` with the object's un-XORed internal position and the *local display
/// player* (`Console+0x298`). Returns `1`, or `-1` when the handle does not resolve.
///
/// This is presentation: the only state it writes is a `MessageWin`. It is here because
/// `general_powers.bhs`'s last statement is a call to it, and a script that cannot make
/// its final call has not run.
fn bubble_text_obj<H: Host + ?Sized>(host: &mut H, args: &[Value]) -> HostResult {
    let text = str_arg(args, 0, "bubble_text_obj: str_text is not a string")?;
    let who_raw = arg(args, 1).as_int();
    let o = arg(args, 2).as_int();

    let Some(who0) = who_zero_based(who_raw) else {
        return Ok(Value::Int(-1));
    };
    let flags = host.leader_flags(who0)?;
    if flags & leader_flag::VALID == 0 || flags & leader_flag::PRESENT == 0 {
        return Ok(Value::Int(-1));
    }
    if !(0..=object_band::MAX_OBJECT_O).contains(&o) {
        return Ok(Value::Int(-1));
    }
    if !host.object_band_probe(who0, o)?.alive {
        return Ok(Value::Int(-1));
    }
    let (xi, yi) = host.object_band_position_internal(who0, o)?;
    let x = xi ^ object_band::POSITION_XOR;
    let y = yi ^ object_band::POSITION_XOR;
    let display = host.local_display_player()?;
    host.add_bubble_message(&text, x, y, display)?;
    Ok(Value::Int(1))
}

